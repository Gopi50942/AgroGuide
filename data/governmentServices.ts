export function searchGovernmentServices(queryText: string): GovernmentService[] {
  const q = queryText.trim().toLowerCase();
  if (!q) return GOVERNMENT_SERVICES.filter((s) => s.active);
  return GOVERNMENT_SERVICES.filter(
    (s) =>
      s.active &&
      (s.name.toLowerCase().includes(q) ||
        (s.nameTa && s.nameTa.toLowerCase().includes(q)) ||
        s.description.toLowerCase().includes(q) ||
        (s.descriptionTa && s.descriptionTa.toLowerCase().includes(q)) ||
        s.category.toLowerCase().includes(q))
  );
}
